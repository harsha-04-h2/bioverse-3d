export function getFigure(id: string): FigureDef | undefined {
  return figures.find((f) => f.id === id);
}

export function figuresForChapter(
  classLevel: 11 | 12,
  chapterNo: number
): FigureDef[] {
  return figures.filter(
    (f) => f.classLevel === classLevel && f.chapterNo === chapterNo
  );
}

export function readyFigureCount(): number {
  return figures.filter((f) => f.status === "ready").length;
}
