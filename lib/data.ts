function unitFor(ranges: [number, number, string][], n: number): string {
  const r = ranges.find(([a, b]) => n >= a && n <= b);
  return r ? r[2] : "";
}

export const chapters: ChapterDef[] = [
  ...C11_TITLES.map((title, i) => ({
    classLevel: 11 as const,
    number: i + 1,
    title,
    unit: unitFor(C11_UNITS, i + 1),
  })),
  ...C12_TITLES.map((title, i) => ({
    classLevel: 12 as const,
    number: i + 1,
    title,
    unit: unitFor(C12_UNITS, i + 1),
  })),
];

export function chapterTitle(classLevel: 11 | 12, chapterNo: number): string {
  return (
    chapters.find((c) => c.classLevel === classLevel && c.number === chapterNo)
      ?.title ?? ""
  );
}

